const PDFDocument = require('pdfkit');
const Student = require('../models/Student');

const calculateGrade = (percentage) => {
  if (percentage >= 90) return 'A+';
  if (percentage >= 80) return 'A';
  if (percentage >= 70) return 'B+';
  if (percentage >= 60) return 'B';
  if (percentage >= 50) return 'C';
  return 'F';
};

exports.generateResultCard = async (req, res) => {
  try {
    const student = await Student.findById(req.params.id);
    if (!student) {
      return res.status(404).json({ message: 'Student not found' });
    }

    const total = student.subject1 + student.subject2 + student.subject3 +
                  student.subject4 + student.subject5;
    const percentage = ((total / 500) * 100).toFixed(2);
    const grade = calculateGrade(percentage);
    const result = percentage >= 40 ? 'PASS' : 'FAIL';

    // PDF banao
    const doc = new PDFDocument({ margin: 50 });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition',
      `attachment; filename=result_${student.rollNumber}.pdf`);

    doc.pipe(res);

    // Header
    doc.fontSize(22).font('Helvetica-Bold')
       .fillColor('#667eea')
       .text('STUDENT RESULT MANAGEMENT SYSTEM', { align: 'center' });

    doc.moveDown(0.5);
    doc.fontSize(12).font('Helvetica')
       .fillColor('#7f8c8d')
       .text('Official Result Card', { align: 'center' });

    // Divider
    doc.moveDown(1);
    doc.moveTo(50, doc.y).lineTo(550, doc.y)
       .strokeColor('#667eea').lineWidth(2).stroke();

    // Student Info
    doc.moveDown(1);
    doc.fontSize(14).font('Helvetica-Bold')
       .fillColor('#2c3e50')
       .text('Student Information', { underline: true });

    doc.moveDown(0.5);
    doc.fontSize(12).font('Helvetica').fillColor('#2c3e50');
    doc.text(`Name         : ${student.name}`);
    doc.text(`Roll Number  : ${student.rollNumber}`);

    // Marks Table
    doc.moveDown(1);
    doc.fontSize(14).font('Helvetica-Bold')
       .fillColor('#2c3e50')
       .text('Subject Wise Marks', { underline: true });

    doc.moveDown(0.5);
    doc.fontSize(12).font('Helvetica').fillColor('#2c3e50');

    const subjects = [
      { name: 'Subject 1', marks: student.subject1 },
      { name: 'Subject 2', marks: student.subject2 },
      { name: 'Subject 3', marks: student.subject3 },
      { name: 'Subject 4', marks: student.subject4 },
      { name: 'Subject 5', marks: student.subject5 },
    ];

    subjects.forEach(s => {
      doc.text(`${s.name}     : ${s.marks} / 100`);
    });

    // Result Summary
    doc.moveDown(1);
    doc.moveTo(50, doc.y).lineTo(550, doc.y)
       .strokeColor('#667eea').lineWidth(1).stroke();

    doc.moveDown(1);
    doc.fontSize(14).font('Helvetica-Bold').fillColor('#2c3e50');
    doc.text(`Total Marks  : ${total} / 500`);
    doc.text(`Percentage   : ${percentage}%`);
    doc.text(`Grade        : ${grade}`);

    doc.moveDown(1);
    const resultColor = result === 'PASS' ? '#27ae60' : '#e74c3c';
    doc.fontSize(20).font('Helvetica-Bold')
       .fillColor(resultColor)
       .text(`Result: ${result}`, { align: 'center' });

    // Footer
    doc.moveDown(2);
    doc.fontSize(10).font('Helvetica')
       .fillColor('#7f8c8d')
       .text('Generated by Student Result Management System',
         { align: 'center' });

    doc.end();

  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};